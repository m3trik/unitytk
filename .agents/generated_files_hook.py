"""Claude Code PreToolUse hook: refuse a hand edit to a generated C# file.

A ``*.g.cs`` (and its ``.meta``) is written by a generator in m3trik/scripts
from a declaration in Python, and its ``// <auto-generated>`` header names that
generator; an edit by hand is lost on the next run and fails
``check_csharp.py --check``. So an Edit or Write to one is denied, with the
generator to run instead. The generators themselves write through Python, which
no hook sees. Registered in ``.claude/settings.json``.

Claude Code runs it as ``python``, with no shell, and hands the event as JSON on
stdin. It imports only the standard library, and anything it cannot read passes:
a broken hook must never block an unrelated edit.
"""
import json
import re
import sys
from pathlib import Path

SUFFIXES = (".g.cs", ".g.cs.meta")
GENERATOR = re.compile(r"m3trik/scripts/\w+\.py")
#: Who writes a *.g.cs whose header names none (a new file, say).
GENERATORS = "m3trik/scripts/sync_operation_contract.py or m3trik/scripts/sync_scene_records.py"


def generator_of(path):
    """The generator *path*'s header names, or None."""
    try:
        with open(path, encoding="utf-8-sig", errors="replace") as handle:
            head = handle.read(600)
    except OSError:
        return None
    if not head.lstrip().startswith("// <auto-generated>"):
        return None
    match = GENERATOR.search(head.split("// </auto-generated>")[0])
    return match.group(0) if match else None


def main():
    try:
        event = json.loads(sys.stdin.buffer.read().decode("utf-8", "replace") or "{}")
        target = str((event.get("tool_input") or {}).get("file_path") or "")
    except (ValueError, AttributeError):
        return
    name = target.replace("\\", "/").rsplit("/", 1)[-1]
    if not name.endswith(SUFFIXES):
        return
    source = Path(target[: -len(".meta")] if name.endswith(".meta") else target)
    generator = generator_of(source)
    reason = (
        f"{name} is generated: never edit it by hand. Change its declaration in "
        f"Python, then run python {generator or GENERATORS} from the workspace "
        "root (a hand edit fails m3trik/scripts/check_csharp.py --check)."
    )
    decision = {"hookEventName": "PreToolUse", "permissionDecision": "deny",
                "permissionDecisionReason": reason}
    print(json.dumps({"hookSpecificOutput": decision}))


if __name__ == "__main__":
    try:
        main()
    except Exception:  # never block an edit for a fault of the hook's own
        pass
